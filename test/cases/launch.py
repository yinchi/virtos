"""Launching a command: `$PATH` lookup, the executable bit, programs vs scripts vs binary data,
scripts run as commands (scoped, with inherited stdio), `source` and `sh`."""


def write_script(s, path, *lines):
    s.run(f"echo '{lines[0]}' > {path}")
    for line in lines[1:]:
        s.run(f"echo '{line}' >> {path}")


def run(ctx):
    s, check = ctx.s, ctx.check
    s.run("mkdir /root/bin")
    write_script(s, "/root/bin/hi", "echo hello from hi")

    # ---------------------------------------------------------------- $PATH
    check("an unset PATH means /usr/bin", s.run("cat /root/bin/hi"), "echo hello from hi\n")
    check("a command in a directory not on the path is not found", s.run("hi"), "hi: command not found\n")
    check("...status 127", s.status("hi")[1], 127)
    check("a file without the exec bit is refused", s.run("PATH=/root/bin hi"), "hi: Permission denied\n")
    check("...status 126", s.status("PATH=/root/bin hi")[1], 126)
    s.run("chmod +x /root/bin/hi")
    check("with the bit, a one-shot PATH finds it", s.run("PATH=/root/bin:/usr/bin hi"), "hello from hi\n")
    check("the one-shot PATH is gone afterwards", s.run("hi"), "hi: command not found\n")
    s.run("export PATH=/root/bin:/usr/bin")
    check("an exported PATH is searched in order", s.run("hi"), "hello from hi\n")
    check("programs on later entries are found", s.run("echo still works"), "still works\n")
    check("an empty PATH finds nothing", s.run("PATH= echo x"), "echo: command not found\n")
    check("empty entries are skipped, not the working directory",
          s.run("cd /root/bin") + s.run("PATH=:/usr/bin hi"), "hi: command not found\n")
    check("a relative entry is relative to the working directory", s.run("PATH=.:/usr/bin hi"), "hello from hi\n")
    check("a nonexistent entry is skipped", s.run("PATH=/nosuch:/root/bin:/usr/bin hi"), "hello from hi\n")
    s.run("cd /root")
    write_script(s, "/root/bin/ls", "echo shadowed ls")
    s.run("chmod +x /root/bin/ls")
    check("an earlier PATH entry shadows a later one", s.run("ls /usr/bin | head -n 1"), "ls: too many arguments\n")
    check("...and the real one is still reachable by path", s.run("/usr/bin/ls /usr/bin | head -n 1"), "cat\n")
    s.run("rm /root/bin/ls")

    # ---------------------------------------------------------------- paths and the file's kind
    check("a name with a slash is a path, never searched", s.run("bin/hi"), "hello from hi\n")
    check("./ works", s.run("cd /root/bin") + s.run("./hi"), "hello from hi\n")
    s.run("cd /root")
    check("a missing path", s.run("./nosuch"), "./nosuch: No such file or directory\n")
    check("...status 127", s.status("./nosuch")[1], 127)
    check("a directory", s.run("/usr"), "/usr: Is a directory\n")
    check("...status 126", s.status("/usr")[1], 126)
    s.run("head -c 8 /usr/bin/cat | tail -c 4 > /root/junk")
    s.run("chmod +x /root/junk")
    check("a non-ELF file with a NUL is binary data", s.run("./junk"), "./junk: cannot execute binary file: Exec format error\n")
    check("...status 126", s.status("./junk")[1], 126)
    s.run("echo 'text' > /root/plain")
    check("a text file without the exec bit is refused", s.run("./plain"), "./plain: Permission denied\n")
    s.run("chmod +x /root/plain")
    check("a text file with it runs as a script (and its commands run)", s.run("./plain"), "text: command not found\n")
    s.run("echo -e '\\xff\\xfe' > /root/latin")
    s.run("chmod +x /root/latin")
    check("a script that is not UTF-8 is refused", s.run("./latin"), "./latin: not valid UTF-8\n")
    s.run("echo -n > /root/empty")
    s.run("chmod +x /root/empty")
    check("an empty executable is an empty script", s.status("./empty"), ("", 0))
    s.run("echo '#!/bin/nosuchinterpreter' > /root/shebang")
    s.run("echo 'echo ran' >> /root/shebang")
    s.run("chmod +x /root/shebang")
    check("#! is just a comment: the shell is the only interpreter", s.run("./shebang"), "ran\n")
    s.run("cp /usr/bin/cat /root/mycat")
    check("a copied program has lost its exec bit", s.run("./mycat /root/plain"), "./mycat: Permission denied\n")
    s.run("chmod +x /root/mycat")
    check("with it back, it runs", s.run("./mycat /root/plain"), "text\n")

    # ---------------------------------------------------------------- scripts as commands
    write_script(s, "/root/bin/scoped", "cd /tmp", "export LEAK=1", "SETHERE=1", "pwd")
    s.run("chmod +x /root/bin/scoped")
    check("a script runs its lines", s.run("scoped"), "/tmp\n")
    check("its cd does not leak", s.run("pwd"), "/root\n")
    check("its exports do not leak", s.run("printenv LEAK"), "")
    check("its assignments do not leak", s.run("echo [$SETHERE]"), "[]\n")
    check("a script takes no arguments", s.run("scoped a"), "scoped: too many arguments\n")
    check("a script's status is its last command's", s.status("scoped")[1], 0)
    write_script(s, "/root/bin/failing", "cat /nosuch")
    s.run("chmod +x /root/bin/failing")
    check("...a failing last command", s.status("failing"), ("cat: /nosuch: cannot open\n", 1))
    write_script(s, "/root/bin/recur", "recur")
    s.run("chmod +x /root/bin/recur")
    out = s.run("recur")
    check("a script that runs itself is stopped", "too many levels of scripts" in out, True)
    check("...and the shell is fine", s.run("echo alive"), "alive\n")
    write_script(s, "/root/bin/sees", "printenv FROMPARENT")
    s.run("chmod +x /root/bin/sees")
    check("a script sees the parent's exported variables", s.run("export FROMPARENT=yes") + s.run("sees"), "yes\n")
    check("...and not its unexported ones", s.run("HIDDEN=1") + s.run("printenv HIDDEN"), "")

    # ---------------------------------------------------------------- stdio inheritance
    write_script(s, "/root/bin/three", "seq 3")
    s.run("chmod +x /root/bin/three")
    check("a script's output can be redirected", s.run("three > /root/o") + s.run("cat /root/o"), "1\n2\n3\n")
    check("...and piped", s.run("three | tail -n 1"), "3\n")
    check("...and appended", s.run("three >> /root/o") + s.run("wc -l < /root/o"), "6\n")
    write_script(s, "/root/bin/reader", "cat")
    s.run("chmod +x /root/bin/reader")
    check("a script's stdin can be redirected", s.run("reader < /root/o | wc -l"), "6\n")
    write_script(s, "/root/bin/twice", "cat", "cat")
    s.run("chmod +x /root/bin/twice")
    s.run("seq 5 > /root/five")
    check("commands in a script share one stdin: the second cat finds it at EOF, not rewound",
          s.run("twice < /root/five"), "1\n2\n3\n4\n5\n")
    write_script(s, "/root/bin/mixed", "echo a", "echo b > /root/inner", "echo c")
    s.run("chmod +x /root/bin/mixed")
    check("a redirect inside overrides the inherited one",
          s.run("mixed > /root/outer") + s.run("cat /root/outer") + s.run("cat /root/inner"), "a\nc\nb\n")
    write_script(s, "/root/bin/outerscript", "mixed", "echo d")
    s.run("chmod +x /root/bin/outerscript")
    check("nested scripts inherit in turn", s.run("outerscript > /root/o2") + s.run("cat /root/o2"), "a\nc\nd\n")
    check("a script can be a pipeline stage", s.run("seq 3 | reader | sort -r"), "3\n2\n1\n")
    write_script(s, "/root/bin/errs", "cat /nosuch")
    s.run("chmod +x /root/bin/errs")
    check("2>&1 on a script catches its errors", s.run("errs > /root/e 2>&1") + s.run("cat /root/e"), "cat: /nosuch: cannot open\n")
    check("a script's redirect that cannot be opened stops it", s.run("three > /nosuchdir/x"), "/nosuchdir/x: cannot create\n")

    # ---------------------------------------------------------------- source, ., sh
    write_script(s, "/root/sourced", "cd /tmp", "export SRC=1", "S2=2")
    check("source runs the file in the shell itself", s.run("source /root/sourced") + s.run("pwd"), "/tmp\n")
    check("...so its exports stay", s.run("printenv SRC"), "1\n")
    check("...and its variables", s.run("echo $S2"), "2\n")
    s.run("cd /root")
    s.run("unset SRC")
    check(". is source", s.run(". /root/sourced") + s.run("pwd"), "/tmp\n")
    s.run("cd /root")
    check("source needs no exec bit", s.status("source /root/sourced")[1], 0)
    s.run("cd /root")
    check("source finds a bare name through PATH", s.run("cp /root/sourced /root/bin/viapath") + s.run("source viapath") + s.run("pwd"), "/tmp\n")
    s.run("cd /root")
    check("source of a missing file", s.run("source /nosuch"), "source: /nosuch: not found\n")
    check("source of a directory", s.run("source /usr"), "source: /usr: is a directory\n")
    check("source with no file", s.run("source"), "source: usage: source FILE\n")
    check("sh runs it scoped", s.run("sh /root/sourced") + s.run("pwd"), "/root\n")
    check("source output can be redirected", s.run("source /root/bin/three > /root/o3") + s.run("cat /root/o3"), "1\n2\n3\n")
    check("source can be piped", s.run("source /root/bin/three | tail -n 1"), "3\n")
    check("the exit status is the file's last line's", s.status("source /root/bin/failing")[1], 1)
